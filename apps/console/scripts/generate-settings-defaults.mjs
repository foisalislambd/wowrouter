// Generates src/lib/settings-defaults.ts from the configuration schema (schema/antirion-config.schema.json):
// every member with a `default`, nested as in the configuration document. The settings endpoints
// return only the values that are stored, so the console shows these when a value is not set.
//
//   node scripts/generate-settings-defaults.mjs           writes the file
//   node scripts/generate-settings-defaults.mjs --check   fails when the committed file is not current
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = resolve(
  root,
  process.env.ANTIRION_CONFIG_SCHEMA ?? '../schema/antirion-config.schema.json',
);
const outPath = resolve(root, 'src/lib/settings-defaults.ts');

const isObject = (v) => typeof v === 'object' && v !== null && !Array.isArray(v);

/** A schema node with its `$ref` followed; members next to the `$ref` (a default) win. */
function deref(schema, node, seen = new Set()) {
  if (!isObject(node) || typeof node.$ref !== 'string') return node;
  if (seen.has(node.$ref)) return node;
  seen.add(node.$ref);
  const name = node.$ref.replace(/^#\/\$defs\//, '');
  const target = deref(schema, schema.$defs?.[name], seen);
  const merged = { ...target, ...node };
  delete merged.$ref;
  return merged;
}

/** The defaults under a node: its own `default`, with its named members' defaults laid over it. */
function defaults(schema, raw, depth = 0) {
  const node = deref(schema, raw);
  if (!isObject(node) || depth > 32) return undefined;
  const own = node.default;
  if (!isObject(node.properties)) return own;
  const out = isObject(own) ? { ...own } : {};
  for (const [key, child] of Object.entries(node.properties)) {
    const value = defaults(schema, child, depth + 1);
    if (value !== undefined) out[key] = value;
  }
  if (Object.keys(out).length > 0) return out;
  return own;
}

/** Prettier's print width in this repository. */
const WIDTH = 110;
const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const quote = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/** A value as TypeScript in the repository's Prettier style (objects always expanded). */
function literal(value, indent) {
  if (value === null) return 'null';
  if (typeof value === 'string') return quote(value);
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  if (Array.isArray(value)) return `[${value.map((v) => literal(v, indent)).join(', ')}]`;
  const keys = Object.keys(value);
  if (keys.length === 0) return '{}';
  const pad = '  '.repeat(indent + 1);
  const quoteKeys = keys.some((k) => !IDENT.test(k));
  const rows = keys.map((k) => {
    const head = `${pad}${quoteKeys || !IDENT.test(k) ? quote(k) : k}: `;
    const v = value[k];
    const line = `${head}${literal(v, indent + 1)},`;
    if (!Array.isArray(v) || line.length <= WIDTH) return line;
    // Too long for one line: one item per line, as Prettier breaks it.
    const items = v.map((item) => `${pad}  ${literal(item, indent + 2)},`);
    return `${head}[\n${items.join('\n')}\n${pad}],`;
  });
  return `{\n${rows.join('\n')}\n${'  '.repeat(indent)}}`;
}

/** The generated file's text for a schema. */
function render(schema) {
  const all = defaults(schema, { properties: schema.properties }) ?? {};
  return `// Generated by scripts/generate-settings-defaults.mjs from schema/antirion-config.schema.json; do not edit.
// Run \`pnpm settings:defaults\` after the schema changes; \`pnpm test\` fails while this file is stale.

/** The gateway's built-in value of every setting the configuration schema gives a default. */
export const SETTINGS_DEFAULTS = ${literal(all, 0)} as const;
`;
}

const text = render(JSON.parse(readFileSync(schemaPath, 'utf8')));
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(outPath, 'utf8');
  } catch {
    current = '';
  }
  if (current !== text) {
    console.error('src/lib/settings-defaults.ts is out of date: run `pnpm settings:defaults`.');
    process.exit(1);
  }
  console.log('settings-defaults: current');
} else {
  writeFileSync(outPath, text);
  console.log('settings-defaults: written');
}
